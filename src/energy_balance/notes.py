"""Weekly note. One page of numbers generated from the latest public data, with two
sections left blank on purpose: the analyst's read and what would change it. The code
writes the numbers; the view is written by hand and committed with the note."""
from __future__ import annotations

import pandas as pd

from .distillate import diesel_crack, five_year_deviation
from .positioning import managed_money_net, zscore


def _f(x, fmt="{:+,.0f}", na="n/a"):
    return na if x is None or pd.isna(x) else fmt.format(x)


def build_note(eia_feat: pd.DataFrame, cot: pd.DataFrame, daily: pd.DataFrame, cfg: dict, regime: str | None = None,
               release_date: pd.Timestamp | None = None, nowcast: pd.DataFrame | None = None, cot_ulsd: pd.DataFrame | None = None) -> str:
    e = eia_feat.dropna(subset=["crude_reported_change_kb"]); wk = e.index[-1]; r = e.iloc[-1]
    rel = release_date if release_date is not None else wk + pd.Timedelta(days=5)
    px = daily.loc[:rel + pd.Timedelta(days=2)].dropna(subset=["wti_cushing"]); last, prev = px.iloc[-1], px.iloc[-6] if len(px) > 5 else px.iloc[0]
    L = [f"# Weekly balance note, week ending {wk.date()}", "",
         f"EIA release {pd.Timestamp(rel).date()}. Prices through {px.index[-1].date()}. Regime label: {regime or 'n/a'}.",
         "Generated by `scripts/make_note.py` from public data. Numbers only; the two sections at the end are written by hand.", "",
         "## Crude", "",
         "| item | value |", "| --- | --- |",
         f"| Reported commercial stock change | {_f(r['crude_reported_change_kb'])} kb |",
         f"| Implied by flows (production + imports - exports - refinery inputs) | {_f(r['crude_implied_change_kb'])} kb |",
         f"| EIA adjustment (reported minus implied) | {_f(r['crude_adjustment_kb'])} kb{' , flagged: more than ' + str(cfg['model']['adjustment_flag_sd']) + ' sd' if bool(r.get('adjustment_flag', False)) else ''} |",
         f"| Naive consensus proxy ({cfg['model']['consensus_window_weeks']} week trailing mean) | {_f(r.get('crude_consensus_proxy_kb'))} kb |",
         f"| Surprise vs proxy | {_f(r['crude_surprise_kb'])} kb, z {_f(r['crude_surprise_z'], '{:+.2f}')} |",
         f"| Refinery utilization | {_f(r.get('refinery_utilization'), '{:.1f}')} percent |",
         f"| Cushing stocks | {_f(r.get('crude_stocks_cushing'), '{:,.0f}')} kb |", ""]
    if "distillate_stocks" in e:
        dev = five_year_deviation(e["distillate_stocks"]).iloc[-1]
        L += ["## Distillate", "", "| item | value |", "| --- | --- |",
              f"| Reported stock change | {_f(r['distillate_reported_change_kb'])} kb |",
              f"| Implied by flows | {_f(r['distillate_implied_change_kb'])} kb |",
              f"| Surprise vs proxy | {_f(r['distillate_surprise_kb'])} kb, z {_f(r['distillate_surprise_z'], '{:+.2f}')} |",
              f"| Stocks | {_f(r['distillate_stocks'], '{:,.0f}')} kb, {_f(dev, '{:+.1f}')} percent vs five-year average for the same week |",
              f"| Days of supply | {_f(r['distillate_days_of_supply'], '{:.1f}')} |", ""]
    L += ["## Prices", "", "| item | latest | five trading days earlier |", "| --- | --- | --- |",
          f"| WTI Cushing, USD/bbl | {_f(last.get('wti_cushing'), '{:.2f}')} | {_f(prev.get('wti_cushing'), '{:.2f}')} |"]
    if "brent" in px: L.append(f"| Brent, USD/bbl | {_f(last.get('brent'), '{:.2f}')} | {_f(prev.get('brent'), '{:.2f}')} |")
    if "ulsd_nyh" in px:
        ck = diesel_crack(px["ulsd_nyh"], px["wti_cushing"])
        L.append(f"| NY Harbor diesel crack vs WTI, USD/bbl | {_f(ck.iloc[-1], '{:.2f}')} | {_f(ck.iloc[-6] if len(ck) > 5 else ck.iloc[0], '{:.2f}')} |")
    L.append("")
    def pos(c, label):
        c = c.loc[:rel + pd.Timedelta(days=2) - pd.Timedelta(days=8)] if len(c) else c          # only reports public by the note date
        if c.empty: return []
        net = managed_money_net(c); z = zscore(net, cfg["model"]["zscore_window_weeks"])
        return [f"| {label} managed money net | {_f(net.iloc[-1])} contracts | z {_f(z.iloc[-1], '{:+.2f}')} | positions as of {(c.index[-1] + pd.Timedelta(days=4)).date()} |"]
    rows = pos(cot, "WTI") + (pos(cot_ulsd, "ULSD") if cot_ulsd is not None else [])
    if rows: L += ["## Positioning (CFTC, disaggregated futures only)", "", "| item | net | one-year z | as of |", "| --- | --- | --- | --- |", *rows, ""]
    if nowcast is not None and not nowcast.empty:
        L += ["## Refiner margin nowcast (quarter in progress)", "",
              "| company | quarter | price days so far | benchmark crack QTD | nowcast USD/bbl | band | last reported | change |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for _, n in nowcast.iterrows():
            L.append(f"| {n['ticker']} | {n['quarter']} | {int(n['days_in_quarter_so_far'])} | {n['crack']:.2f} | {n['pred']:.2f} | {n['band_low']:.2f} to {n['band_high']:.2f} | {n['naive']:.2f} | {n['change_vs_last_reported']:+.2f} |")
        L += ["", "OLS on the quarter-average Gulf Coast 3-2-1 crack, trained only on quarters already reported."]
        if "extrapolating" in nowcast and nowcast["extrapolating"].astype(str).str.lower().eq("true").any():
            L += ["The quarter-to-date crack is outside the range the model was fitted on, so the nowcast is an extrapolation and the band understates the uncertainty."]
        L += [""]
    L += ["## My read", "", "_Two or three sentences, written by hand after looking at the numbers above._", "",
          "## What would change my mind", "", "_One observable, with a number and a date._", ""]
    return "\n".join(L)
